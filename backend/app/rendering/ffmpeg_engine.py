"""FFmpeg render engine: validated plan -> filter_complex -> MP4. No user-controlled string reaches a shell;
all numbers are formatted from validated floats/ints, and file names are generated by us."""
from __future__ import annotations
import math
from pathlib import Path
from typing import Callable, Optional
from ..config import get_settings
from ..core.process import run_ffmpeg_progress
from .transition_engine import SUPPORTED_XFADE

COLOR_FILTERS = {"none": "", "cinematic": "eq=contrast=1.1:saturation=0.9:gamma=0.97,vignette=PI/6", "vivid": "eq=saturation=1.3:contrast=1.05", "bw": "hue=s=0"}
PAD_THRESHOLD = 3.5   # aspect mismatch above which we letterbox on a blurred background instead of cropping


def _f(x: float) -> str:
    return f"{x:.4f}"


def _esc_path(p: str) -> str:
    return p.replace("\\", "\\\\").replace(":", "\\:").replace("'", "\\'")


def reframe_chain(k: int, src_w: int, src_h: int, W: int, H: int, focus_x: float) -> str:
    sa, ta = src_w / src_h, W / H
    mismatch = max(sa / ta, ta / sa)
    if mismatch > PAD_THRESHOLD:
        return (f"split=2[ta{k}][tb{k}];[ta{k}]scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},boxblur=20:2[bg{k}];"
                f"[tb{k}]scale={W}:{H}:force_original_aspect_ratio=decrease[fg{k}];[bg{k}][fg{k}]overlay=(W-w)/2:(H-h)/2,setsar=1,format=yuv420p")
    f = max(W / src_w, H / src_h)
    sw, sh = int(math.ceil(src_w * f / 2) * 2), int(math.ceil(src_h * f / 2) * 2)
    sw, sh = max(sw, W), max(sh, H)
    x = int(min(max(focus_x * sw - W / 2, 0), sw - W)) // 2 * 2
    y = int((sh - H) / 2) // 2 * 2
    return f"scale={sw}:{sh}:flags=bicubic,crop={W}:{H}:{x}:{y},setsar=1,format=yuv420p"


def build_graph(plan: dict, W: int, H: int, has_audio: bool, ass_name: Optional[str], music: bool, fontsdir: Optional[str]) -> tuple[str, float, list]:
    clips = plan["clips"]
    src = plan["source"]
    cfg = plan["config"]
    fps = plan["output"]["fps"]
    chains: list[str] = []
    seg_idx, all_segs = 0, []   # block = list of segment indexes; new block starts where a transition overlaps
    block_info: list[dict] = []
    for i, c in enumerate(clips):
        if i == 0 or c["transition_in"]["duration"] <= 0:
            if i == 0 or not block_info:
                block_info.append({"segs": [], "len": 0.0, "trans": None})
            # hard cut: merge into the previous block
        else:
            block_info.append({"segs": [], "len": 0.0, "trans": c["transition_in"]})
        for s in c["segments"]:
            a, b = s["start"], s["end"]
            v = f"[{seg_idx}:v]setpts=PTS-STARTPTS,fps={fps},{reframe_chain(seg_idx, src['width'], src['height'], W, H, c.get('focus_x', 0.5))}[v{seg_idx}]"
            chains.append(v)
            if has_audio:
                chains.append(f"[{seg_idx}:a]asetpts=PTS-STARTPTS,aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo[a{seg_idx}]")
            all_segs.append((a, b))
            block_info[-1]["segs"].append(seg_idx)
            block_info[-1]["len"] += b - a
            seg_idx += 1
    for bi, blk in enumerate(block_info):
        ins = "".join(f"[v{k}]" + (f"[a{k}]" if has_audio else "") for k in blk["segs"])
        chains.append(f"{ins}concat=n={len(blk['segs'])}:v=1:a={1 if has_audio else 0}[bv{bi}]" + (f"[ba{bi}]" if has_audio else ""))
    cur_v, cur_a, cur_len = "bv0", "ba0", block_info[0]["len"]
    for bi in range(1, len(block_info)):
        t = block_info[bi]["trans"]
        d = t["duration"]
        typ = t["type"] if t["type"] in SUPPORTED_XFADE else "fade"
        chains.append(f"[{cur_v}][bv{bi}]xfade=transition={typ}:duration={_f(d)}:offset={_f(cur_len - d)}[xv{bi}]")
        if has_audio:
            chains.append(f"[{cur_a}][ba{bi}]acrossfade=d={_f(d)}[xa{bi}]")
        cur_v, cur_a = f"xv{bi}", f"xa{bi}"
        cur_len = cur_len + block_info[bi]["len"] - d
    vpost = []
    if COLOR_FILTERS.get(cfg["color_preset"]):
        vpost.append(COLOR_FILTERS[cfg["color_preset"]])
    if ass_name:
        vpost.append(f"ass={ass_name}" + (f":fontsdir={fontsdir}" if fontsdir else ""))
    vpost.append("format=yuv420p")
    chains.append(f"[{cur_v}]{','.join(vpost)}[outv]")
    if has_audio:
        fo = max(0.0, cur_len - 0.5)
        tail = []
        if cfg.get("normalize_audio", True):
            tail.append("loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000")
        tail += [f"afade=t=in:st=0:d=0.3", f"afade=t=out:st={_f(fo)}:d=0.5", "aformat=sample_fmts=fltp:channel_layouts=stereo"]
        if music:
            chains.append(f"[{cur_a}]asplit=2[sp1][sp2]")
            chains.append(f"[{len(all_segs)}:a]aformat=sample_fmts=fltp:channel_layouts=stereo,aresample=48000,atrim=0:{_f(cur_len)},asetpts=PTS-STARTPTS,volume=0.35[mus]")
            chains.append("[mus][sp2]sidechaincompress=threshold=0.04:ratio=10:attack=20:release=400[duck]")
            chains.append("[sp1][duck]amix=inputs=2:duration=first:dropout_transition=0[mix]")
            chains.append(f"[mix]{','.join(tail)}[outa]")
        else:
            chains.append(f"[{cur_a}]{','.join(tail)}[outa]")
    return ";".join(chains), cur_len, all_segs


def render(plan: dict, src: Path, out: Path, work: Path, W: int, H: int, preview: bool = False, ass_text: Optional[str] = None,
           music: Optional[Path] = None, on_progress: Optional[Callable[[float], None]] = None) -> dict:
    s = get_settings()
    has_audio = bool(plan["source"]["has_audio"])
    work.mkdir(parents=True, exist_ok=True)
    ass_name = None
    if ass_text:
        ass_name = "subs.ass"
        (work / ass_name).write_text(ass_text, encoding="utf-8")
    fonts = None
    if s.fonts_dir.exists() and any(s.fonts_dir.glob("*.[to]tf")):
        import shutil
        shutil.copytree(s.fonts_dir, work / "fonts", dirs_exist_ok=True, ignore=shutil.ignore_patterns("*.txt", "*.md"))
        fonts = "fonts"   # relative to the ffmpeg working directory: no absolute-path escaping needed
    use_music = bool(music) and has_audio
    graph, total, segs = build_graph(plan, W, H, has_audio, ass_name, use_music, fonts)
    (work / "filter.txt").write_text(graph, encoding="utf-8")
    args: list[str] = []
    for a, b in segs:   # one seeked input per segment: no cross-segment frame buffering (keeps RAM flat on long sources)
        args += ["-ss", _f(a), "-t", _f(b - a), "-i", str(src)]
    if use_music:
        args += ["-stream_loop", "-1", "-i", str(music)]
    args += ["-/filter_complex", str(work / "filter.txt"), "-map", "[outv]"]
    args += ["-map", "[outa]"] if has_audio else ["-an"]
    args += ["-c:v", "libx264", "-preset", "ultrafast" if preview else "veryfast", "-crf", "30" if preview else "21", "-pix_fmt", "yuv420p",
             "-r", str(plan["output"]["fps"]), "-t", _f(total + 0.05)]
    if has_audio:
        args += ["-c:a", "aac", "-b:a", "96k" if preview else "160k", "-ar", "48000"]
    args += ["-movflags", "+faststart", str(out)]
    run_ffmpeg_progress(args, total, on_progress, cwd=work)
    return {"expected_duration": total, "filter_graph_chars": len(graph), "used_music": use_music, "burned_subtitles": bool(ass_name)}
